"""Pydantic schemas for Post-Debate Analytical Report generation."""

from pydantic import BaseModel, Field


class ParticipantArgumentAnalysis(BaseModel):
    participant_id: str = Field(description="UUID of the debate participant.")
    display_name: str = Field(description="Display name of the debater.")
    role: str = Field(description="Role in the debate (DEBATER or MODERATOR).")
    core_stance: str = Field(
        description="Concise 1-2 sentence summary of the participant's main thesis."
    )
    key_arguments: list[str] = Field(
        description="2 to 4 strongest arguments or mechanisms presented by this speaker."
    )
    evidence_usage_notes: str = Field(
        description="Assessment of how well this speaker grounded claims in verifiable facts."
    )
    logical_consistency_notes: str = Field(
        description="Notes on coherence, responsiveness to counter-points, or logical gaps."
    )


class ReportClaimSummary(BaseModel):
    speaker_name: str = Field(description="Speaker who made the claim.")
    normalized_claim: str = Field(description="The extracted factual claim.")
    verdict: str = Field(
        description="SUPPORTED, REFUTED, PARTIALLY_SUPPORTED, CONTRADICTORY_EVIDENCE, or INSUFFICIENT_EVIDENCE."
    )
    explanation: str = Field(
        description="Brief explanation of the evidence assessment."
    )
    sources: list[str] = Field(
        default_factory=list,
        description="Titles or URLs of cited evidence sources, if any.",
    )


class GeneratedDebateReport(BaseModel):
    """Structured output generated by Gemini for post-debate synthesis."""

    executive_summary: str = Field(
        description="Neutral 3-4 sentence synthesis of the debate progression, key clashes, and evidence balance."
    )
    participant_analyses: list[ParticipantArgumentAnalysis] = Field(
        description="Structured analytical breakdown for each speaking debater."
    )
    claim_highlights: list[ReportClaimSummary] = Field(
        description="Summary of key factual claims evaluated during the debate."
    )
    unanswered_questions: list[str] = Field(
        description="2 to 4 important factual or policy questions left unresolved by the debate."
    )
    moderator_takeaways: list[str] = Field(
        description="2 to 3 objective takeaways for the human moderator and audience (do not declare a simplistic winner)."
    )


class ReportTranscriptInput(BaseModel):
    speaker_name: str
    role: str
    text: str
    timestamp: str


class ReportClaimInput(BaseModel):
    speaker_name: str
    normalized_claim: str
    verdict: str
    confidence: float | None = None
    explanation: str
    sources: list[str] = Field(default_factory=list)


class ReportParticipantInput(BaseModel):
    participant_id: str
    display_name: str
    role: str
    vote_count: int = 0


class DebateReportRequest(BaseModel):
    debate_id: str
    title: str
    topic: str
    description: str | None = None
    category: str | None = None
    core_summary: str | None = None
    participants: list[ReportParticipantInput] = Field(default_factory=list)
    transcripts: list[ReportTranscriptInput] = Field(default_factory=list)
    claims: list[ReportClaimInput] = Field(default_factory=list)
    total_votes: int = 0


class DebateReportResponse(BaseModel):
    debate_id: str
    summary: str
    report_data: dict
    model_name: str